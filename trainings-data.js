/* مفتاح الخطة حسب النمط والمدينة */
function teknovaPlanKey(modeId, cityId) {
  return modeId === "online" ? "online" : modeId + ":" + cityId;
}
function teknovaGetPlan(trackId, modeId, cityId) {
  const tr = TEKNOVA_TRAININGS[trackId];
  if (!tr || !tr.plans) return null;
  return tr.plans[teknovaPlanKey(modeId, cityId)] || null;
}

